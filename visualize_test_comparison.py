"""
visualize_test_comparison.py
Visualizes and compares radio maps generated by:
1. main_batch_cluster.py (Static Ray-Traced Jammers)
2. main_no_interactive.py (Curved Trajectory & Multi-Jammer Aggregation)
"""

import os
import sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

def main():
    test_dir = "/pomplun/scratch01/cs_research/l.gonzalezgudino001/sionna_rt_jamming/test_validation_slurm"
    artifact_dir = "/pomplun/share_home/l.gonzalezgudino001/.gemini/antigravity-ide/brain/68b5f52a-7341-494d-a6b9-df393eb41cba"
    os.makedirs(artifact_dir, exist_ok=True)

    # 1. Load batch_cluster data
    batch_dir = os.path.join(test_dir, "batch_cluster", "single_static_jammers")
    batch_watts_path = os.path.join(batch_dir, "range_parts", "watts_00000_00002.npy")
    batch_pos_path = os.path.join(batch_dir, "positions.npy")

    batch_watts = np.load(batch_watts_path) # shape: (2, 300, 300)
    batch_pos = np.load(batch_pos_path)     # shape: (2, 2) or (2, 3)

    # Convert Watts to dBW
    noise_floor = 8e-15
    batch_dbw_0 = 10.0 * np.log10(batch_watts[0] + noise_floor)
    batch_dbw_1 = 10.0 * np.log10(batch_watts[1] + noise_floor)

    # 2. Load no_interactive data
    no_int_base_path = os.path.join(test_dir, "no_interactive", "trajectories", "radio_maps", "rm_watts_traj_dur5s_vel03mps_00.npy")
    no_int_combo_path = os.path.join(test_dir, "no_interactive", "sim_results", "combo_0000_k02", "rss_aggregated.npy")

    no_int_base_watts = np.load(no_int_base_path)   # shape: (5, H, W)
    no_int_base_dbw = 10.0 * np.log10(no_int_base_watts[0] + noise_floor) # Frame 0

    no_int_combo_rss = np.load(no_int_combo_path)   # shape: (5, H, W) - already dBW or watts
    # Check if linear or dBW
    if np.nanmin(no_int_combo_rss) >= 0:
        no_int_combo_dbw = 10.0 * np.log10(no_int_combo_rss[0] + noise_floor)
    else:
        no_int_combo_dbw = no_int_combo_rss[0]

    # Create 2x2 comparison figure
    fig, axes = plt.subplots(2, 2, figsize=(14, 12))
    plt.subplots_adjust(wspace=0.25, hspace=0.3)

    vmin, vmax = -140.0, -40.0

    # Panel 1: Batch Cluster - Static Jammer 0
    im0 = axes[0, 0].imshow(batch_dbw_0, origin="lower", cmap="viridis", vmin=vmin, vmax=vmax)
    axes[0, 0].set_title(f"main_batch_cluster: Static Jammer #0\nPos: ({batch_pos[0, 0]:.1f}, {batch_pos[0, 1]:.1f})", fontsize=11, fontweight="bold")
    axes[0, 0].set_xlabel("X (cells)")
    axes[0, 0].set_ylabel("Y (cells)")
    fig.colorbar(im0, ax=axes[0, 0], fraction=0.046, pad=0.04, label="RSS (dBW)")

    # Panel 2: Batch Cluster - Static Jammer 1
    im1 = axes[0, 1].imshow(batch_dbw_1, origin="lower", cmap="viridis", vmin=vmin, vmax=vmax)
    axes[0, 1].set_title(f"main_batch_cluster: Static Jammer #1\nPos: ({batch_pos[1, 0]:.1f}, {batch_pos[1, 1]:.1f})", fontsize=11, fontweight="bold")
    axes[0, 1].set_xlabel("X (cells)")
    axes[0, 1].set_ylabel("Y (cells)")
    fig.colorbar(im1, ax=axes[0, 1], fraction=0.046, pad=0.04, label="RSS (dBW)")

    # Panel 3: No-Interactive - Dynamic Jammer Base 0 (Frame 0)
    im2 = axes[1, 0].imshow(no_int_base_dbw, origin="lower", cmap="viridis", vmin=vmin, vmax=vmax)
    axes[1, 0].set_title("main_no_interactive: Curved Jammer #0 (Frame 0)\nDynamic trajectory (5s @ 3m/s)", fontsize=11, fontweight="bold")
    axes[1, 0].set_xlabel("X (cells)")
    axes[1, 0].set_ylabel("Y (cells)")
    fig.colorbar(im2, ax=axes[1, 0], fraction=0.046, pad=0.04, label="RSS (dBW)")

    # Panel 4: No-Interactive - Multi-Jammer Combo (2 jammers)
    im3 = axes[1, 1].imshow(no_int_combo_dbw, origin="lower", cmap="viridis", vmin=vmin, vmax=vmax)
    axes[1, 1].set_title("main_no_interactive: Multi-Jammer Combo (K=2)\nAggregated interference map", fontsize=11, fontweight="bold")
    axes[1, 1].set_xlabel("X (cells)")
    axes[1, 1].set_ylabel("Y (cells)")
    fig.colorbar(im3, ax=axes[1, 1], fraction=0.046, pad=0.04, label="RSS (dBW)")

    fig.suptitle("Sionna RT Jamming - Radio Map Comparison\n[main_batch_cluster vs main_no_interactive]", fontsize=14, fontweight="bold", y=0.98)

    # Save to artifact dir and scratch
    out_artifact = os.path.join(artifact_dir, "radio_maps_comparison.png")
    out_scratch = os.path.join(test_dir, "radio_maps_comparison.png")

    fig.savefig(out_artifact, dpi=150, bbox_inches="tight")
    fig.savefig(out_scratch, dpi=150, bbox_inches="tight")
    plt.close(fig)

    print(f"Comparison saved to:\n  {out_artifact}\n  {out_scratch}")

if __name__ == "__main__":
    main()
